// Japanese → Simplified Chinese disease name dictionary.
// Keys are normalized with normalizeName() (full-width ASCII/parentheses → half-width),
// so variants like "鳥インフルエンザ(Ｈ５Ｎ１）" and "鳥インフルエンザ（Ｈ５Ｎ１）" share one entry.
// Unknown names fall back to the original Japanese string.

export function normalizeName(name) {
  if (!name) return ''
  return String(name)
    // Full-width ASCII letters/digits/punctuation → half-width
    .replace(/[！-～]/g, ch => String.fromCharCode(ch.charCodeAt(0) - 0xFEE0))
    .replace(/　/g, ' ')
    .trim()
}

